"""Locality-ordered pages with a C++ SIMD shortlist (OpenEvolve main2 winner, ablation).
IVF (n/512 lists, HNSW over the centroids); each list is reordered by recursive
bisection so a 4 KB page holds near neighbours. In DRAM: faiss IndexIVFPQFastScan
(4-bit PQ of the residuals, dim/4 sub-quantizers = dim/8 bytes per vector, ids = disk
positions) plus a dim/8-byte 8-bit PQ of what it leaves (residual of the residual),
which re-estimates the shortlist before pages are chosen. A query takes the `shortlist` best positions from the SIMD scan of its
nprobe lists, reads the `pages` pages that hold the best-ranked of them (one I/O
round) and ranks the vectors there exactly. Generated by make_fastscan.py.
"""

import faiss
import numpy as np

SEARCH_POINTS = [
    {"nprobe": 48, "shortlist": 256, "pages": 16},
    {"nprobe": 64, "shortlist": 256, "pages": 16},
    {"nprobe": 64, "shortlist": 384, "pages": 16},
    {"nprobe": 80, "shortlist": 384, "pages": 16},
    {"nprobe": 96, "shortlist": 384, "pages": 16},
    {"nprobe": 64, "shortlist": 384, "pages": 20},
    {"nprobe": 96, "shortlist": 384, "pages": 20},
    {"nprobe": 96, "shortlist": 512, "pages": 24},
]
LOCAL = True
PAGE = 4096


def _local_order(vecs, per_page):
    """Balanced recursive bisection: every leaf is one full page of nearby vectors."""
    n = len(vecs)
    out = np.empty(n, dtype=np.int64)
    rng = np.random.default_rng(1)

    def split(idx, lo):
        m = idx.size
        if m <= per_page:
            out[lo : lo + m] = idx
            return
        x = vecs[idx]
        xc = x - x.mean(0)
        v = rng.standard_normal(x.shape[1]).astype(np.float32)
        for _ in range(5):  # power iteration for the principal axis
            v = xc.T @ (xc @ v)
            v /= np.linalg.norm(v) + 1e-12
        left = ((-(-m // per_page)) // 2) * per_page
        o = np.argsort(xc @ v, kind="stable")
        for _ in range(3):  # balanced 2-means refinement of the split direction
            w = xc[o[left:]].mean(0) - xc[o[:left]].mean(0)
            o = np.argsort(xc @ w, kind="stable")
        split(idx[o[:left]], lo)
        split(idx[o[left:]], lo + left)

    split(np.arange(n), 0)
    return out


def build(ctx):
    data = ctx.data
    n, dim = data.shape
    rec = dim * data.dtype.itemsize + 4  # vector + uint32 id
    per_page = PAGE // rec
    nlist = max(16, n // 512)
    faiss.omp_set_num_threads(ctx.threads)

    rng = np.random.default_rng(0)
    sample = np.asarray(
        data[np.sort(rng.choice(n, size=min(n, 20 * nlist), replace=False))],
        dtype=np.float32,
    )
    km = faiss.Kmeans(
        dim, nlist, niter=8, seed=1, verbose=False, spherical=ctx.metric == "IP"
    )
    km.train(sample)
    centroids = km.centroids.astype(np.float32)

    # HNSW over the centroids makes assigning 10M vectors a few minutes, not an hour.
    metric = faiss.METRIC_INNER_PRODUCT if ctx.metric == "IP" else faiss.METRIC_L2
    quant = faiss.IndexHNSWFlat(dim, 32, metric)
    quant.hnsw.efSearch = 64
    quant.add(centroids)
    assign = np.empty(n, dtype=np.int64)
    step = 1_000_000
    for s in range(0, n, step):
        _, a = quant.search(np.asarray(data[s : s + step], dtype=np.float32), 1)
        assign[s : s + step] = a[:, 0]

    raw = np.asarray(data).view(np.uint8).reshape(n, -1)  # the build is not DRAM-capped
    order = np.argsort(assign, kind="stable")  # ids ascending within each cluster
    sizes = np.bincount(assign, minlength=nlist)

    # Page-local layout: each 4 KB page becomes a tight micro-cluster.
    from concurrent.futures import ThreadPoolExecutor

    starts = np.zeros(nlist + 1, dtype=np.int64)
    np.cumsum(sizes, out=starts[1:])

    def _reorder(c):
        ids = order[starts[c] : starts[c + 1]]
        if ids.size <= per_page:
            return ids
        v = raw[ids].view(data.dtype).astype(np.float32)
        return ids[_local_order(v, per_page)]

    if LOCAL:
        with ThreadPoolExecutor(max(1, int(ctx.threads))) as ex:
            order = np.concatenate(list(ex.map(_reorder, range(nlist))))
    faiss.omp_set_num_threads(ctx.threads)
    pages_per = (sizes + per_page - 1) // per_page
    page_start = np.zeros(nlist + 1, dtype=np.int64)
    np.cumsum(pages_per, out=page_start[1:])

    w = ctx.disk_writer("lists")
    vbytes = rec - 4
    pos = 0
    for c in range(nlist):
        ids = order[pos : pos + sizes[c]]
        pos += sizes[c]
        recs = np.zeros((pages_per[c] * per_page, rec), dtype=np.uint8)
        recs[:, vbytes:] = 0xFF  # padding records carry id 0xFFFFFFFF
        recs[: ids.size, :vbytes] = raw[ids]
        recs[: ids.size, vbytes:] = ids.astype(np.uint32).view(np.uint8).reshape(-1, 4)
        pages = np.zeros((pages_per[c], PAGE), dtype=np.uint8)
        pages[:, : per_page * rec] = recs.reshape(pages_per[c], per_page * rec)
        w.write_pages(pages)

    # Level 1: 4-bit fast-scan PQ (dim/4 sub-quantizers); level 2: 8-bit PQ (dim/8) of
    # the level-1 error. Vector ids are disk positions; codes2 / kappa rows likewise.
    cstart = np.zeros(nlist + 1, dtype=np.int64)
    np.cumsum(sizes, out=cstart[1:])
    fs = faiss.IndexIVFPQFastScan(quant, dim, nlist, dim // 4, 4, metric)
    fs.by_residual = True
    tr_idx = np.sort(rng.choice(n, size=min(n, 400_000), replace=False))
    trx = np.ascontiguousarray(np.asarray(data[tr_idx], dtype=np.float32))
    fs.train(trx)
    _, tra = quant.search(trx, 1)
    tr1 = np.ascontiguousarray(trx - centroids[tra[:, 0]])
    tr2 = np.ascontiguousarray(tr1 - fs.pq.decode(fs.pq.compute_codes(tr1)))
    pq2 = faiss.ProductQuantizer(dim, dim // 8, 8)
    pq2.train(tr2)
    codes2 = np.empty((n, pq2.code_size), dtype=np.uint8)
    kappa = np.empty(n, dtype=np.float32)
    for s in range(0, n, step):
        ids = order[s : s + step]
        xs = np.ascontiguousarray(raw[ids].view(data.dtype).astype(np.float32))
        fs.add_with_ids(xs, np.arange(s, s + ids.size, dtype=np.int64))
        r1 = np.ascontiguousarray(xs - centroids[assign[ids]])
        x1 = fs.pq.decode(fs.pq.compute_codes(r1))
        c2 = pq2.compute_codes(np.ascontiguousarray(r1 - x1))
        e2 = pq2.decode(c2)
        codes2[s : s + ids.size] = c2
        kappa[s : s + ids.size] = 2.0 * (x1 * e2).sum(1) + (e2 * e2).sum(1)
    got = np.array([fs.invlists.list_size(c) for c in range(nlist)])
    assert np.array_equal(got, sizes), (
        "faiss list assignment differs from the page layout"
    )
    # written straight to the index directory: serialize_index + deserialize_index would
    # hold three copies of the index at once (the search container is capped at 1 GB)
    faiss.write_index(fs, str(ctx._dir / "mem" / "fs.faiss"))
    ctx.save_mem("codes2", codes2)
    ctx.save_mem(
        "pq2", faiss.vector_to_array(pq2.centroids).reshape(pq2.M, 256, pq2.dsub)
    )
    ctx.save_mem("kappa", kappa)
    ctx.save_mem("centroids", centroids)
    ctx.save_mem("page_start", page_start)
    ctx.save_mem("cstart", cstart)
    ctx.save_json(
        "layout",
        {"dim": dim, "dtype": data.dtype.str, "rec": rec, "per_page": per_page},
    )


class Searcher:
    def __init__(self, ctx, params):
        try:  # CPU time counts every thread: keep BLAS single-threaded
            from threadpoolctl import threadpool_limits

            self._tp = threadpool_limits(1)
        except Exception:
            pass
        faiss.omp_set_num_threads(1)
        self.fs = faiss.read_index(str(ctx._dir / "mem" / "fs.faiss"))
        self.codes2 = ctx.mem("codes2")
        self.pq2 = np.ascontiguousarray(ctx.mem("pq2"), dtype=np.float32)
        self.kappa = ctx.mem("kappa")
        self.centroids = ctx.mem("centroids")
        self.page_start = ctx.mem("page_start").astype(np.int64)
        self.cstart = ctx.mem("cstart").astype(np.int64)
        lay = ctx.json("layout")
        self.dim, self.rec, self.per_page = lay["dim"], lay["rec"], lay["per_page"]
        self.dtype = np.dtype(lay["dtype"])
        self.ip = ctx.metric == "IP"
        nprobe = min(int(params["nprobe"]), self.fs.nlist - 1)
        self.fs.nprobe = nprobe
        faiss.downcast_index(self.fs.quantizer).hnsw.efSearch = max(
            64, int(1.5 * nprobe)
        )
        self.shortlist = int(params["shortlist"])
        self.budget = int(params["pages"])
        self.mr = np.arange(self.pq2.shape[0])

    def search(self, query, k, io):
        q = np.ascontiguousarray(query, dtype=np.float32)
        d1, hits = self.fs.search(q[None, :], self.shortlist)
        ok = hits[0] >= 0
        pos, d1 = hits[0][ok], d1[0][ok]
        if pos.size == 0:
            return np.zeros(k, dtype=np.int64)
        lst = np.searchsorted(self.cstart, pos, side="right") - 1
        e2 = self.pq2[self.mr, self.codes2[pos]].reshape(pos.size, -1)
        if self.ip:  # faiss returns <q, c + x1> for IP (larger is better)
            est = -(d1 + e2 @ q)
        else:
            est = d1 - 2.0 * ((q - self.centroids[lst]) * e2).sum(1) + self.kappa[pos]
        o = np.argsort(est)
        pg = (self.page_start[lst] + (pos - self.cstart[lst]) // self.per_page)[o]
        _, first = np.unique(pg, return_index=True)  # pages in order of their best hit
        page_ids = pg[np.sort(first)[: self.budget]]
        pages = io.read("lists", np.sort(page_ids))
        recs = pages[:, : self.per_page * self.rec].reshape(-1, self.rec)
        vbytes = self.rec - 4
        ids = np.ascontiguousarray(recs[:, vbytes:]).view(np.uint32).ravel()
        vecs = (
            np.ascontiguousarray(recs[:, :vbytes]).view(self.dtype).astype(np.float32)
        )
        dist = -(vecs @ q) if self.ip else ((vecs - q) ** 2).sum(1)
        dist[ids == 0xFFFFFFFF] = np.inf
        kk = min(k, dist.size)
        top = (
            np.argpartition(dist, kk - 1)[:kk]
            if kk < dist.size
            else np.arange(dist.size)
        )
        return ids[top[np.argsort(dist[top])]].astype(np.int64)
