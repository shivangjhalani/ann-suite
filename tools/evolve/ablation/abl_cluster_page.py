def _local_order(vecs, per_page):
    """Balanced recursive bisection: every leaf is one full page of nearby vectors."""
    n = len(vecs)
    out = np.empty(n, dtype=np.int64)
    rng = np.random.default_rng(1)

    def split(idx, lo):
        m = idx.size
        if m <= per_page:
            out[lo : lo + m] = idx
            return
        x = vecs[idx]
        xc = x - x.mean(0)
        v = rng.standard_normal(x.shape[1]).astype(np.float32)
        for _ in range(5):  # power iteration for the principal axis
            v = xc.T @ (xc @ v)
            v /= np.linalg.norm(v) + 1e-12
        left = ((-(-m // per_page)) // 2) * per_page
        o = np.argsort(xc @ v, kind="stable")
        for _ in range(3):  # balanced 2-means refinement of the split direction
            w = xc[o[left:]].mean(0) - xc[o[:left]].mean(0)
            o = np.argsort(xc @ w, kind="stable")
        split(idx[o[:left]], lo)
        split(idx[o[left:]], lo + left)

    split(np.arange(n), 0)
    return out


def build(ctx):
    data = ctx.data
    n, dim = data.shape
    rec = dim * data.dtype.itemsize + 4  # vector + uint32 id
    per_page = PAGE // rec
    nlist = max(16, n // 512)
    faiss.omp_set_num_threads(ctx.threads)

    rng = np.random.default_rng(0)
    sample = np.asarray(
        data[np.sort(rng.choice(n, size=min(n, 20 * nlist), replace=False))], dtype=np.float32
    )
    km = faiss.Kmeans(dim, nlist, niter=8, seed=1, verbose=False, spherical=ctx.metric == "IP")
    km.train(sample)
    centroids = km.centroids.astype(np.float32)

    # HNSW over the centroids makes assigning 10M vectors a few minutes, not an hour.
    metric = faiss.METRIC_INNER_PRODUCT if ctx.metric == "IP" else faiss.METRIC_L2
    quant = faiss.IndexHNSWFlat(dim, 32, metric)
    quant.hnsw.efSearch = 64
    quant.add(centroids)
    assign = np.empty(n, dtype=np.int64)
    step = 1_000_000
    for s in range(0, n, step):
        _, a = quant.search(np.asarray(data[s : s + step], dtype=np.float32), 1)
        assign[s : s + step] = a[:, 0]

    raw = np.asarray(data).view(np.uint8).reshape(n, -1)  # the build is not DRAM-capped
    order = np.argsort(assign, kind="stable")  # ids ascending within each cluster
    sizes = np.bincount(assign, minlength=nlist)

    # Page-local layout: each 4 KB page becomes a tight micro-cluster.
    from concurrent.futures import ThreadPoolExecutor

    starts = np.zeros(nlist + 1, dtype=np.int64)
    np.cumsum(sizes, out=starts[1:])

    def _reorder(c):
        ids = order[starts[c] : starts[c + 1]]
        if ids.size <= per_page:
            return ids
        v = raw[ids].view(data.dtype).astype(np.float32)
        return ids[_local_order(v, per_page)]

    if LOCAL:
        with ThreadPoolExecutor(max(1, int(ctx.threads))) as ex:
            order = np.concatenate(list(ex.map(_reorder, range(nlist))))
    faiss.omp_set_num_threads(ctx.threads)
    pages_per = (sizes + per_page - 1) // per_page
    page_start = np.zeros(nlist + 1, dtype=np.int64)
    np.cumsum(pages_per, out=page_start[1:])

    w = ctx.disk_writer("lists")
    vbytes = rec - 4
    pos = 0
    for c in range(nlist):
        ids = order[pos : pos + sizes[c]]
        pos += sizes[c]
        recs = np.zeros((pages_per[c] * per_page, rec), dtype=np.uint8)
        recs[:, vbytes:] = 0xFF  # padding records carry id 0xFFFFFFFF
        recs[: ids.size, :vbytes] = raw[ids]
        recs[: ids.size, vbytes:] = ids.astype(np.uint32).view(np.uint8).reshape(-1, 4)
        pages = np.zeros((pages_per[c], PAGE), dtype=np.uint8)
        pages[:, : per_page * rec] = recs.reshape(pages_per[c], per_page * rec)
        w.write_pages(pages)

    # Residual PQ codes in cluster (= disk) order: code row index -> disk slot implicitly.
    cstart = np.zeros(nlist + 1, dtype=np.int64)
    np.cumsum(sizes, out=cstart[1:])
    tr_idx = np.sort(rng.choice(n, size=min(n, 200_000), replace=False))
    tr = np.asarray(data[tr_idx], dtype=np.float32) - centroids[assign[tr_idx]]
    for M in CODE_MS:
        if dim % M:
            continue
        pq = faiss.ProductQuantizer(dim, M, 8)
        trc = np.ascontiguousarray(tr)
        pq.train(trc)
        m2 = REFINE.get(M)
        pq2 = None
        if m2 and dim % m2 == 0:
            tr2 = np.ascontiguousarray(trc - pq.decode(pq.compute_codes(trc)))
            pq2 = faiss.ProductQuantizer(dim, m2, 8)
            pq2.train(tr2)
            codes2 = np.empty((n, m2), dtype=np.uint8)
            del tr2
        codes = np.empty((n, M), dtype=np.uint8)
        for s in range(0, n, step):
            ids = order[s : s + step]
            res = raw[ids].view(data.dtype).astype(np.float32) - centroids[assign[ids]]
            res = np.ascontiguousarray(res)
            c1 = pq.compute_codes(res)
            codes[s : s + step] = c1
            if pq2 is not None:
                codes2[s : s + step] = pq2.compute_codes(np.ascontiguousarray(res - pq.decode(c1)))
        ctx.save_mem(f"codes{M}", codes)
        ctx.save_mem(f"pqc{M}", faiss.vector_to_array(pq.centroids).reshape(M, 256, dim // M))
        del codes
        if pq2 is not None:
            ctx.save_mem(f"rcodes{M}_{m2}", codes2)
            ctx.save_mem(
                f"rpqc{M}_{m2}", faiss.vector_to_array(pq2.centroids).reshape(m2, 256, dim // m2)
            )
            del codes2

    ctx.save_mem("centroids", centroids)
    ctx.save_mem("page_start", page_start)
    ctx.save_mem("cstart", cstart)
    ctx.save_json("layout", {"dim": dim, "dtype": data.dtype.str, "rec": rec, "per_page": per_page})


class Searcher:
    def __init__(self, ctx, params):
        try:  # CPU time counts every thread: keep BLAS single-threaded
            from threadpoolctl import threadpool_limits

            self._tp = threadpool_limits(1)
        except Exception:
            pass
        faiss.omp_set_num_threads(1)
        self.centroids = np.ascontiguousarray(ctx.mem("centroids"), dtype=np.float32)
        self.page_start = ctx.mem("page_start").astype(np.int64)
        self.cstart = ctx.mem("cstart").astype(np.int64)
        lay = ctx.json("layout")
        self.dim, self.rec, self.per_page = lay["dim"], lay["rec"], lay["per_page"]
        self.dtype = np.dtype(lay["dtype"])
        self.ip = ctx.metric == "IP"
        self.nprobe = min(int(params["nprobe"]), len(self.centroids) - 1)
        self.rank = params[
            "rank"
        ]  # "page": best pages by code distance; "vec": pages of best vectors
        self.budget = int(params["budget"])  # pages read ("page") or vectors re-ranked ("vec")
        self.M = 8
        self.codes = np.ascontiguousarray(ctx.mem("codes8"))
        self.pqc = np.ascontiguousarray(ctx.mem("pqc8").astype(np.float32))
        self.pqc_norm = (self.pqc**2).sum(-1)
        self.pqcT = np.ascontiguousarray(self.pqc.transpose(0, 2, 1))  # (M, dsub, 256)
        metric = faiss.METRIC_INNER_PRODUCT if self.ip else faiss.METRIC_L2
        self.cq_index = faiss.IndexHNSWFlat(self.dim, 32, metric)
        self.cq_index.hnsw.efConstruction = 80
        self.cq_index.add(self.centroids)
        self.cq_index.hnsw.efSearch = max(64, int(1.5 * self.nprobe))
        self.pstart_hi = self.page_start[1:]

    def _lut(self, q, probe, cq_probe):
        M, dsub, P = self.M, self.pqc.shape[2], probe.size
        if self.ip:
            lut1 = -np.matmul(q.reshape(M, 1, dsub), self.pqcT)
            lut = np.ascontiguousarray(np.broadcast_to(lut1, (M, P, 256)), dtype=np.float32)
            return lut, (-cq_probe).astype(np.float32)
        qrt = np.ascontiguousarray(
            (q[None, :] - self.centroids[probe]).reshape(P, M, dsub).transpose(1, 0, 2)
        )
        lut = np.matmul(qrt, self.pqcT)
        lut *= -2.0
        lut += (qrt**2).sum(-1)[:, :, None]
        lut += self.pqc_norm[:, None, :]
        return np.ascontiguousarray(lut, dtype=np.float32), np.zeros(P, np.float32)

    def search(self, query, k, io):
        q = np.ascontiguousarray(query, dtype=np.float32)
        Dc, Ic = self.cq_index.search(q[None, :], self.nprobe)
        ok = Ic[0] >= 0
        probe = Ic[0][ok].astype(np.int64)
        if probe.size == 0:
            return np.zeros(k, dtype=np.int64)
        lut, base = self._lut(q, probe, Dc[0][ok].astype(np.float32))
        lo = self.cstart[probe]
        cnt = self.cstart[probe + 1] - lo
        ps = self.page_start[probe]
        if self.rank == "page":
            npg = int((self.pstart_hi[probe] - ps).sum())
            pd = np.empty(npg, np.float32)
            pp = np.empty(npg, np.int64)
            n = _page_min(lut, self.codes, lo, cnt, ps, base, self.per_page, pd, pp)
            pd, pp = pd[:n], pp[:n]
            r = min(n, self.budget)
            page_ids = pp[np.argpartition(pd, r - 1)[:r]] if r < n else pp
        else:
            tot = int(cnt.sum())
            adc = np.empty(tot, np.float32)
            _adc_scan(lut, self.codes, lo, cnt, adc)
            pidx = np.repeat(np.arange(probe.size), cnt)
            offs = np.arange(tot) - np.repeat(np.cumsum(cnt) - cnt, cnt)
            adc += base[pidx]
            r = min(tot, self.budget)
            sel = np.argpartition(adc, r - 1)[:r] if r < tot else np.arange(tot)
            page_ids = np.unique(ps[pidx[sel]] + offs[sel] // self.per_page)
        pages = io.read("lists", np.sort(page_ids))
        recs = pages[:, : self.per_page * self.rec].reshape(-1, self.rec)
        vbytes = self.rec - 4
        ids = np.ascontiguousarray(recs[:, vbytes:]).view(np.uint32).ravel()
        if self.dtype == np.uint8:
            dist = np.empty(ids.size, np.float32)
            _score_u8(recs, self.dim, q, self.ip, dist)
        else:
            vecs = np.ascontiguousarray(recs[:, :vbytes]).view(self.dtype).astype(np.float32)
            dist = -(vecs @ q) if self.ip else ((vecs - q) ** 2).sum(1)
            dist[ids == 0xFFFFFFFF] = np.inf
        kk = min(k, dist.size)
        top = np.argpartition(dist, kk - 1)[:kk] if kk < dist.size else np.arange(dist.size)
        return ids[top[np.argsort(dist[top])]].astype(np.int64)
